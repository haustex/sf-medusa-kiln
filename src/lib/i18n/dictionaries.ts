/** Brand name and location come from theme.config.ts: every "{brand}" / "{location}" in the copy is filled once here. */
const withBrand = <T,>(value: T): T => {
  if (typeof value === "string") return value.replaceAll("{brand}", config.brand.name).replaceAll("{location}", config.brand.location) as T
  if (Array.isArray(value)) return value.map(withBrand) as T
  if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, withBrand(v)])) as T
  return value
}
const dictionaries = { id: withBrand(id), en: withBrand(en) }

